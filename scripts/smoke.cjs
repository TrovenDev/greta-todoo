const { _electron: electron }=require('@playwright/test');
const fs=require('node:fs');
const assert=require('node:assert/strict');
const appVersion=require('../package.json').version;
(async()=>{
  fs.mkdirSync('docs',{recursive:true});
  const testDir=require('node:path').resolve('.test-data/electron');
  const workspace=require('node:path').resolve('.test-data');
  if(!testDir.startsWith(workspace+require('node:path').sep))throw Error('Pasta de teste inválida.');
  fs.rmSync(testDir,{recursive:true,force:true});
  const launchEnv={...process.env,TROVEN_SMOKE:'1'};
  delete launchEnv.ELECTRON_RUN_AS_NODE;
  const app=await electron.launch({args:['.','--force-prefers-reduced-motion'],env:launchEnv,timeout:15000});
  try {
    const page=await app.firstWindow({timeout:15000}); const errors=[];
    page.setDefaultTimeout(10000);
    await page.emulateMedia({reducedMotion:'reduce'});
    await page.reload();
    console.log('Janela Electron iniciada.');
    page.on('pageerror',e=>errors.push(e.message));
    await page.waitForSelector('#version:has-text("'+appVersion+'")');
    console.log('Interface e ponte local prontas.');
    await page.locator('[data-view="today"]').click({force:true});
    await page.locator('#new-task').click({force:true});
    const now=new Date();
    const today=`${now.getFullYear()}-${String(now.getMonth()+1).padStart(2,'0')}-${String(now.getDate()).padStart(2,'0')}`;
    await page.locator('[name="date"]').fill(today);
    await page.locator('[name="title"]').fill('Treinamento do sistema');
    await page.locator('[name="category"]').selectOption('treinamento');
    await page.locator('[name="notes"]').fill('Revisar o fluxo de cadastro e tirar dúvidas.');
    await page.locator('[type="submit"]').click({force:true});
    console.log('Primeira tarefa salva.');
    await page.waitForSelector('.task-title:has-text("Treinamento do sistema")');
    await page.locator('.check').first().click({force:true});
    await page.locator('[data-view="done"]').click({force:true});
    await page.waitForSelector('.task.completed');
    await page.locator('.check').first().click({force:true});
    await page.locator('[data-view="today"]').click({force:true});
    await page.locator('[data-edit]').first().click({force:true});
    await page.locator('[name="title"]').fill('Treinamento · Cadastro de produtos');
    await page.locator('[name="priority"]').selectOption('alta');
    await page.locator('[type="submit"]').click({force:true});
    await page.waitForSelector('.task-title:has-text("Cadastro de produtos")');
    await page.locator('#new-task').click({force:true});
    await page.locator('[name="date"]').fill(today);
    await page.locator('[name="title"]').fill('Conferir lançamentos no sistema');
    await page.locator('[name="category"]').selectOption('sistema');
    await page.locator('[type="submit"]').click({force:true});
    await page.locator('#new-task').click({force:true});
    await page.locator('[name="date"]').fill(today);
    await page.locator('[name="title"]').fill('Alinhamento da equipe');
    await page.locator('[name="category"]').selectOption('reuniao');
    await page.locator('[type="submit"]').click({force:true});
    await page.locator('#search').fill('inexistente');
    await page.waitForSelector('.empty');
    await page.locator('#search').fill('');
    assert.equal(await page.locator('.task').count(),3);
    await page.reload();
    await page.waitForSelector('#version:has-text("'+appVersion+'")');
    await page.waitForSelector('.task');
    assert.equal(await page.locator('.task').count(),3);
    await page.screenshot({path:'docs/visao-geral.png'});
    await page.locator('[data-view="calendar"]').click({force:true});
    await page.waitForSelector('.calendar-layout');
    await page.locator('[data-view="settings"]').click({force:true});
    await page.waitForSelector('#export');
    await app.evaluate(({dialog},filePath)=>{dialog.showSaveDialog=async()=>({canceled:false,filePath});},require('node:path').resolve('.test-data/backup.json'));
    await page.locator('#export').click({force:true});
    await page.waitForSelector('#toast:has-text("Backup exportado")');
    assert.equal(JSON.parse(fs.readFileSync('.test-data/backup.json','utf8')).tasks.length,3);
    await page.locator('#check-settings').click({force:true});
    await page.waitForSelector('#update-message:has-text("aplicativo instalado")');
    await page.locator('[data-view="all"]').click({force:true});
    await page.locator('[data-delete]').first().click({force:true});
    await page.locator('#confirm-delete').click({force:true});
    assert.equal(await page.locator('.task').count(),2);
    assert.deepEqual(errors,[]);
    console.log('PASS: criar, editar, concluir, reabrir, buscar, agenda, preferências, atualizar e excluir.');
  } finally {await app.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
